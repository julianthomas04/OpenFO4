//! The fixed lookup tables: 512 pseudo-random floats (jitter, colour, yaw,
//! height variation) and 512 cosines (slope test).

use std::sync::LazyLock;

use super::mt19937::Mt19937;

pub const TABLE_LEN: usize = 512;
const TABLE_MASK: usize = TABLE_LEN - 1;
const TABLE_SEED: u32 = 1;
/// Scale of the unit-range random values, applied in `f32`.
pub const UNIT_SCALE: f32 = 0.99999;
const TWO_POW_32: f32 = 4_294_967_296.0;
/// Angle step of one cosine table entry (2*pi/512).
const ANGLE_STEP: f32 = 0.012_271_847;
/// Table entries per degree (512/360).
const ENTRIES_PER_DEGREE: f32 = 1.422_222_1;

/// A generator word as a float in `[0, 0.99999)`.
pub fn unit_float(word: u32) -> f32 {
    word as f32 / TWO_POW_32 * UNIT_SCALE
}

static RANDOM_TABLE: LazyLock<[f32; TABLE_LEN]> = LazyLock::new(|| {
    let mut generator = Mt19937::new(TABLE_SEED);
    std::array::from_fn(|_| unit_float(generator.next_u32()))
});

static COSINE_TABLE: LazyLock<[f32; TABLE_LEN]> = LazyLock::new(|| {
    let mut angle = 0.0f32;
    std::array::from_fn(|_| {
        let cosine = angle.cos();
        angle += ANGLE_STEP;
        cosine
    })
});

/// Table entry `counter mod 512`; the counter starts at the product of the
/// cell coordinates and so may be negative.
pub fn random_at(counter: i32) -> f32 {
    RANDOM_TABLE[(counter as u32 as usize) & TABLE_MASK]
}

/// Cosine of a whole-degree angle through the table's 512-step quantisation.
pub fn cosine_of_degrees(degrees: u8) -> f32 {
    COSINE_TABLE[(f32::from(degrees) * ENTRIES_PER_DEGREE) as usize & TABLE_MASK]
}

#[cfg(test)]
#[allow(
    clippy::float_cmp,
    reason = "expected values are exact literals or exact table entries"
)]
mod tests {
    use super::*;

    #[test]
    fn random_table_starts_with_the_documented_values() {
        // The placement table is generated by MT19937 with seed 1 as f32(word)/2^32*0.99999.
        for (index, expected) in [0.417_017_82, 0.997_174_8, 0.720_317_3, 0.932_548]
            .into_iter()
            .enumerate()
        {
            let actual = random_at(index as i32);
            assert!(
                (actual - expected).abs() < 1e-6,
                "[{index}] {actual} vs {expected}"
            );
        }
    }

    #[test]
    fn counter_wraps_at_512_and_accepts_negative_values() {
        assert_eq!(random_at(512), random_at(0));
        assert_eq!(random_at(-1), random_at(511));
        assert_eq!(random_at(-512), random_at(0));
    }

    #[test]
    fn unit_floats_stay_below_one() {
        assert!(unit_float(u32::MAX) < 1.0);
        assert_eq!(unit_float(0), 0.0);
    }

    #[test]
    fn random_table_entries_beyond_the_start_match_the_reference_generator() {
        // Reference: MT19937 init_genrand(1), f32(word)/2^32 * 0.99999.
        assert!((random_at(100) - 0.019_366_765).abs() < 1e-7);
        assert!((random_at(511) - 0.209_490_78).abs() < 1e-7);
    }

    #[test]
    fn cosine_table_is_indexed_by_512ths_of_a_turn() {
        // (degrees, expected cosf(index * 2pi/512) with float32 accumulation, index
        // int(degrees * 1.42222214): 0, 63, 65, 85, 127, 255)
        for (degrees, expected) in [
            (0, 1.0),
            (45, 0.715_731_1),
            (46, 0.698_376_6),
            (60, 0.503_539),
            (90, 0.012_270_814),
            (180, -0.999_924_8),
        ] {
            let actual = cosine_of_degrees(degrees);
            assert!(
                (actual - expected).abs() < 1e-6,
                "{degrees} deg: {actual} vs {expected}"
            );
        }
    }
}
