"""Rules decided by the content of text files: machine-translated shaders, shader disassembly and bulk data."""

import re
from dataclasses import dataclass

from finding import Finding

FLAGS = re.MULTILINE | re.ASCII


@dataclass(frozen=True)
class Fingerprint:
    label: str
    pattern: re.Pattern[str]
    decisive: bool = False


def _fingerprint(label: str, pattern: str, decisive: bool = False) -> Fingerprint:
    return Fingerprint(label, re.compile(pattern, FLAGS), decisive)


# Vocabulary of the installer's DXBC to WGSL emitter (src/installer/shader_translator/wgsl). Hand-written wrappers
# only call translated functions; they never declare these interface structs, temporaries or helper variables.
TRANSLATOR_FINGERPRINTS = (
    _fingerprint("I/O struct field with signature comment ('v0: vec4<f32>, // POSITION0 mask=0x7')", r"^[ \t]*[vo]\d+:\s*vec4<f32>,\s*//.*\bmask=0x[0-9a-f]+", decisive=True),
    _fingerprint("register temporaries ('var r0: vec4<f32>;')", r"^[ \t]*var\s+r\d+:\s*vec4<f32>;", decisive=True),
    _fingerprint("deferred discard flag ('discard_pending')", r"\bdiscard_pending\b", decisive=True),
    _fingerprint("float bit-pattern variable ('bits_3f800000')", r"\bbits_[0-9a-f]{8}\b", decisive=True),
    _fingerprint("entry point 'fn X(i: X_in) -> X_out'", r"\bfn\s+(\w+)\(\s*i:\s*\1_in\s*\)\s*->\s*\1_out\b"),
    _fingerprint("interface struct 'struct X_in' / 'struct X_out'", r"^[ \t]*struct\s+\w+_(?:in|out)\s*\{"),
    _fingerprint("indexable temporaries ('var x0: array<vec4<f32>, N>;')", r"^[ \t]*var\s+x\d+:\s*array<vec4<f32>,\s*\d+>;"),
    _fingerprint("immediate constant buffer ('X_icb')", r"^[ \t]*var<private>\s+\w+_icb\b"),
    _fingerprint("thread-group declarations ('X_workgroup_size_x', 'X_g0')", r"\b\w+_workgroup_size_[xyz]\b|^[ \t]*var<workgroup>\s+\w+_g\d+\b"),
    _fingerprint("numbered 'let tmpN =' temporaries", r"^[ \t]*let\s+tmp\d+\s*="),
)
MIN_WEAK_FINGERPRINTS = 2
TEMP_REGISTER_PATTERN = re.compile(r"\br\d+\b", FLAGS)
MIN_DISTINCT_TEMP_REGISTERS = 8

DXBC_ASSEMBLY_PATTERN = re.compile(
    r"^[ \t]*dcl_(?:globalFlags|input|output|temps|indexableTemp|constantbuffer|resource|sampler|uav|thread_group|tgsm)\w*"
    r"|^[ \t]*(?:vs|ps|cs|gs|hs|ds)_[45]_\d[ \t]*$"
    r"|^//\s*Generated by Microsoft \(R\) HLSL Shader Compiler",
    FLAGS | re.IGNORECASE,
)

MIN_ENCODED_BLOB_CHARS = 128
MIN_HEX_BYTES = 64
MIN_NUMBER_LITERALS = 128
_HEX_BYTE = r"(?:0[xX])?[0-9a-fA-F]{2}(?![0-9A-Za-z_])"
_NUMBER = r"[-+]?(?>(?:0[xX][0-9a-fA-F]+|(?:\d+\.\d*|\d+)(?:[eE][-+]?\d+)?)[fFuUlL]{0,3})(?![0-9A-Za-z_.])"
ENCODED_BLOB_PATTERN = re.compile(rf"(?<![A-Za-z0-9+/])[A-Za-z0-9+/]{{{MIN_ENCODED_BLOB_CHARS},}}={{0,2}}(?![A-Za-z0-9+/])", FLAGS)
HEX_BYTE_TABLE_PATTERN = re.compile(rf"(?<![0-9A-Za-z_]){_HEX_BYTE}(?:[\s,]+{_HEX_BYTE}){{{MIN_HEX_BYTES - 1},}}", FLAGS)
NUMERIC_TABLE_PATTERN = re.compile(rf"(?<![0-9A-Za-z_.]){_NUMBER}(?:[\s,;]+{_NUMBER}){{{MIN_NUMBER_LITERALS - 1},}}", FLAGS)


def _line_of(text: str, offset: int) -> int:
    return text.count("\n", 0, offset) + 1


def check_translated_wgsl(path: str, text: str) -> list[Finding]:
    matched = [(fingerprint, match) for fingerprint in TRANSLATOR_FINGERPRINTS if (match := fingerprint.pattern.search(text))]
    weak = [fingerprint for fingerprint, _ in matched if not fingerprint.decisive]
    if any(fingerprint.decisive for fingerprint, _ in matched) or len(weak) >= MIN_WEAK_FINGERPRINTS:
        first_line = min(_line_of(text, match.start()) for _, match in matched)
        labels = "; ".join(fingerprint.label for fingerprint, _ in matched)
        return [Finding("translated-wgsl", path, f"looks like output of the DXBC to WGSL translator: {labels}", first_line)]

    registers = {match.group() for match in TEMP_REGISTER_PATTERN.finditer(text)}
    if len(registers) >= MIN_DISTINCT_TEMP_REGISTERS:
        return [Finding("translated-wgsl", path, f"uses {len(registers)} distinct DXBC-style temporary registers (r0, r1, ...)")]
    return []


def check_dxbc_assembly(path: str, text: str) -> list[Finding]:
    match = DXBC_ASSEMBLY_PATTERN.search(text)
    if match is None:
        return []
    return [Finding("dxbc-disassembly", path, f"contains shader disassembly ('{match.group().strip()[:60]}')", _line_of(text, match.start()))]


def check_bulk_data(path: str, text: str) -> list[Finding]:
    findings = []
    if match := ENCODED_BLOB_PATTERN.search(text):
        findings.append(Finding("encoded-blob", path, f"contains a {len(match.group())}-character base64/hex run", _line_of(text, match.start())))
    if match := HEX_BYTE_TABLE_PATTERN.search(text):
        findings.append(Finding("hex-byte-table", path, f"contains a table of at least {MIN_HEX_BYTES} hex bytes", _line_of(text, match.start())))
    if match := NUMERIC_TABLE_PATTERN.search(text):
        findings.append(Finding("numeric-table", path, f"contains a run of at least {MIN_NUMBER_LITERALS} numeric literals", _line_of(text, match.start())))
    return findings
